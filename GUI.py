from turtle import Turtle, Screen
huzi = Turtle()
huzi.shape("turtle")
huzi.color("pale violet red","firebrick")
huzi.pensize(5)
huzi.speed(4)
huzi.penup()
huzi.goto(-300, 0)
huzi.pendown()

def right_run():
    huzi.forward(100)
    huzi.right(90)


def move(dis):
    huzi.penup()
    huzi.forward(dis)
    huzi.pendown()


def down(dis):
    huzi.right(90)
    huzi.forward(dis)


def up(distance):
    huzi.backward(distance)


huzi.right(90)
huzi.forward(150)
huzi.penup()
huzi.backward(50)
huzi.pendown()
huzi.left(90)
right_run()
huzi.forward(50)
huzi.backward(150)
huzi.forward(150)

huzi.penup()
huzi.left(135)
huzi.forward(100)
huzi.pendown()
