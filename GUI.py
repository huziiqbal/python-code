huzi.forward(70)
huzi.penup()
huzi.right(90)
huzi.forward(30)
huzi.pendown()
huzi.forward(100)
huzi.right(135)
huzi.forward(100)
huzi.left(135)
huzi.forward(80)
huzi.penup()
huzi.forward(30)
huzi.left(90)
huzi.pendown()
huzi.forward(80)
huzi.penup()
huzi.forward(30)
huzi.dot(20)
